#[test]
fn charls_2_4_5_bidirectional_golden_conformance() {
    for v in GOLDEN_VECTORS {
        // Direction 1: CharLS 2.4.5 encoded -> dcmnorm-jpegls decoded.
        let (decoded, info) = dcmnorm_jpegls::decode_to_bytes(v.charls_encoded)
            .unwrap_or_else(|e| panic!("{}: decode failed: {e}", v.name));
        assert_eq!(info.width, v.width, "{}", v.name);
        assert_eq!(info.height, v.height, "{}", v.name);
        assert_eq!(info.components, v.components, "{}", v.name);
        assert_eq!(info.bits_per_sample, v.bits_per_sample, "{}", v.name);
        assert_eq!(info.near, v.near, "{}", v.name);
        assert_eq!(
            decoded, v.charls_decoded,
            "{}: charls->ours pixel mismatch",
            v.name
        );
        if v.near == 0 {
            assert_eq!(
                decoded, v.original,
                "{}: lossless original mismatch",
                v.name
            );
        }

        // Direction 2: dcmnorm-jpegls encoded -> byte-identical codestream (for <=12-bit)
        // or identical decoded pixels (for 16-bit, where CharLS adds a redundant LSE ID=1).
        let ours = dcmnorm_jpegls::encode_bytes(
            v.original,
            v.width,
            v.height,
            v.components,
            v.bits_per_sample,
            v.near,
            v.interleave_mode,
        )
        .unwrap_or_else(|e| panic!("{}: encode failed: {e}", v.name));
        if v.bits_per_sample <= 12 {
            assert_eq!(
                ours, v.charls_encoded,
                "{}: codestream differs from CharLS 2.4.5",
                v.name
            );
        } else {
            // CharLS 2.4.5 emits an optional 15-byte LSE ID=1 marker for >12-bit;
            // the SOS header + entropy-coded scan payload + EOI must match byte-for-byte.
            let our_sos = ours
                .windows(2)
                .position(|w| w == [0xFF, 0xDA])
                .expect("our SOS marker");
            let charls_sos = v
                .charls_encoded
                .windows(2)
                .position(|w| w == [0xFF, 0xDA])
                .expect("CharLS SOS marker");
            assert_eq!(
                &ours[our_sos..],
                &v.charls_encoded[charls_sos..],
                "{}: 16-bit SOS + scan payload differs from CharLS 2.4.5",
                v.name
            );
            let (roundtripped, _) = dcmnorm_jpegls::decode_to_bytes(&ours).unwrap();
            assert_eq!(
                roundtripped, v.charls_decoded,
                "{}: 16-bit roundtrip mismatch",
                v.name
            );
        }
    }
}
