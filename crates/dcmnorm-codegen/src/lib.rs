fn is_video(uid: &str) -> bool {
    // MPEG-2, MPEG-4 AVC/H.264, HEVC/H.265: 1.2.840.10008.1.2.4.100 - .108 (and their .1 forms)
    uid.strip_prefix("1.2.840.10008.1.2.4.10")
        .and_then(|rest| rest.chars().next())
        .is_some_and(|digit| digit.is_ascii_digit())
}

pub fn transfer_syntaxes() -> Vec<TsEntry> {
    let mut entries: Vec<TsEntry> = dcmnorm_dictionary::uids::TRANSFER_SYNTAXES
        .iter()
        .map(|entry: &UidDictionaryEntryRef<'static>| {
            let uid = entry.uid;
            let registered = TransferSyntaxRegistry.get(uid);
            let native = [
                "1.2.840.10008.1.2",
                "1.2.840.10008.1.2.1",
                "1.2.840.10008.1.2.1.99",
                "1.2.840.10008.1.2.2",
            ];
            let (explicit_vr, big_endian, deflated, encapsulated) = match registered {
                Some(ts) => (
                    ts.explicit_vr(),
                    ts.endianness() == Endianness::Big,
                    matches!(ts.codec(), Codec::Dataset(_)),
                    ts.is_encapsulated_pixel_data(),
                ),
                None => (
                    uid != "1.2.840.10008.1.2" && uid != "1.2.840.10008.1.20",
                    uid == "1.2.840.10008.1.2.2",
                    uid.ends_with(".99")
                        || uid == "1.2.840.10008.1.2.4.95"
                        || uid == "1.2.840.10008.1.2.4.205",
                    !native.contains(&uid) && uid != "1.2.840.10008.1.20",
                ),
            };
            TsEntry {
                keyword: entry.alias,
                uid,
                name: entry.name,
                retired: entry.retired,
                explicit_vr,
                big_endian,
                deflated,
                encapsulated,
                compressed: encapsulated && !ENCAPSULATED_UNCOMPRESSED.contains(&uid),
                lossy: LOSSY.contains(&uid) || is_video(uid),
            }
        })
        .collect();
    entries.sort_by(|a, b| a.keyword.cmp(b.keyword));
    entries
}

