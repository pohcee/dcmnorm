//! Generates the DICOM constants every language binding ships - `Tag`, `VR`, `TransferSyntax`
//! and `SOPClassUID` (#6) - from the same data the Rust side uses: the attribute table of
//! `dcmnorm-dictionary` (keywords, tags, VRs), its UID tables (transfer syntaxes and SOP
//! classes), the transfer syntax registry of `dcmnorm-transcode` (encoding properties) and the
//! `VR` enum of `dcmnorm-core`. Nothing is maintained by hand in the outputs; regenerate with
//! `cargo run -p dcmnorm-codegen` after a dictionary update, and `cargo run -p dcmnorm-codegen --
//! --check` (also the `generated_sources_are_up_to_date` test) fails while they differ.
//!
//! Outputs, relative to the repository root, are [`OUTPUTS`]. The names are the standard
//! keywords (dcm4che's `Tag`/`UID` names), the same in every binding: `Tag.StudyInstanceUID`.

