fn quoted(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn javadoc_text(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace("*/", "*&#47;")
}

fn tag_label(entry: &TagEntry) -> String {
    match &entry.pattern {
        Some(pattern) => format!("({pattern})"),
        None => format!("({:04X},{:04X})", entry.tag >> 16, entry.tag & 0xFFFF),
    }
}

