/// Every output's contents, in [`OUTPUTS`] order.
pub fn generate() -> Vec<GeneratedFile> {
    let tags = tags();
    let vrs = vrs();
    let syntaxes = transfer_syntaxes();
    let sop = sop_classes();
    let contents = [
        java_tag(&tags),
        java_vr(&vrs),
        java_transfer_syntax(&syntaxes),
        java_sop_class(&sop),
        node_js(&tags, &vrs, &syntaxes, &sop),
        node_dts(&tags, &vrs, &syntaxes, &sop),
        python_constants(&tags, &vrs, &syntaxes, &sop),
    ];
    OUTPUTS
        .iter()
        .zip(contents)
        .map(|(path, contents)| GeneratedFile { path, contents })
        .collect()
}

/// The outputs under `root` that are missing or differ from what [`generate`] produces.
pub fn stale_outputs(root: &Path) -> Vec<&'static str> {
    generate()
        .into_iter()
        .filter(|file| {
            std::fs::read_to_string(root.join(file.path))
                .ok()
                .as_deref()
                != Some(file.contents.as_str())
        })
        .map(|file| file.path)
        .collect()
}

/// Write every output under `root`, returning the ones that changed.
pub fn write_outputs(root: &Path) -> std::io::Result<Vec<&'static str>> {
    let mut changed = Vec::new();
    for file in generate() {
        let path = root.join(file.path);
        if std::fs::read_to_string(&path).ok().as_deref() != Some(file.contents.as_str()) {
            std::fs::write(&path, &file.contents)?;
            changed.push(file.path);
        }
    }
    Ok(changed)
}
