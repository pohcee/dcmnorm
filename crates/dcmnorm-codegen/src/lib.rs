pub struct TagEntry {
    pub keyword: &'static str,
    pub tag: u32,
    pub vr: String,
    /// `"60xx,3000"`-style pattern for a repeating-group entry (its constant is the first group).
    pub pattern: Option<String>,
}

pub fn tags() -> Vec<TagEntry> {
    let mut seen = BTreeSet::new();
    let mut entries = Vec::new();
    for entry in dcmnorm_dictionary::tags::ENTRIES {
        let (tag, pattern) = match entry.tag {
            TagRange::Single(tag) => (tag, None),
            TagRange::Group100(tag) => (
                tag,
                Some(format!("{:02X}xx,{:04X}", tag.group() >> 8, tag.element())),
            ),
            TagRange::Element100(tag) => (
                tag,
                Some(format!("{:04X},{:02X}xx", tag.group(), tag.element() >> 8)),
            ),
            _ => continue,
        };
        if !seen.insert(entry.alias) {
            continue;
        }
        let vr = match entry.vr {
            dcmnorm_core::dictionary::VirtualVr::Exact(vr) => vr.to_string().to_owned(),
            dcmnorm_core::dictionary::VirtualVr::Xs => "US or SS".to_owned(),
            dcmnorm_core::dictionary::VirtualVr::Ox => "OB or OW".to_owned(),
            dcmnorm_core::dictionary::VirtualVr::Px => "OB or OW".to_owned(),
            dcmnorm_core::dictionary::VirtualVr::Lt => "US, SS or OW".to_owned(),
            other => other.relaxed().to_string().to_owned(),
        };
        entries.push(TagEntry {
            keyword: entry.alias,
            tag: (u32::from(tag.group()) << 16) | u32::from(tag.element()),
            vr,
            pattern,
        });
    }
    entries.sort_by(|a, b| a.tag.cmp(&b.tag).then(a.keyword.cmp(b.keyword)));
    entries
}

/// How a VR's values are held (what a binding's typed accessors read): text, a binary integer,
/// a binary float, an attribute tag, raw bytes, or a sequence. PS3.5 Table 6.2-1.
pub fn vr_kind(vr: VR) -> &'static str {
    match vr {
        VR::SS | VR::US | VR::SL | VR::UL | VR::SV | VR::UV => "int",
        VR::FL | VR::FD => "float",
        VR::AT => "tag",
        VR::OB | VR::OW | VR::OF | VR::OD | VR::OL | VR::OV | VR::UN => "binary",
        VR::SQ => "sequence",
        _ => "string",
    }
}

/// Every VR the Rust `VR` enum knows, in alphabetical order.
pub fn vrs() -> Vec<VR> {
    let mut vrs = Vec::new();
    for a in b'A'..=b'Z' {
        for b in b'A'..=b'Z' {
            let code = String::from_utf8(vec![a, b]).expect("ascii");
            if let Ok(vr) = VR::from_str(&code) {
                if vr.to_string() == code {
                    vrs.push(vr);
                }
            }
        }
    }
    vrs
}

